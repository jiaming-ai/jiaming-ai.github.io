#!/usr/bin/env python3
"""Build data/recipes.js (ingredients per dish, for the shopping list).

Sources:
  tools/ingredients.tsv  vocabulary: 中文名 <TAB> English <TAB> aisle <TAB> unit (g or 个)
  tools/recipes.tsv      dish id <TAB> tokens joined by ';'
Token forms:  name:qty   |   name (seasoning, no quantity)   |   name~English~aisle~unit[:qty]  (defines a new ingredient)
Quantities are for 2 people; the page scales them. Usage: python3 tools/build_recipes.py [--report]
"""
import json, re, sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PANTRY = "调味"


def tsv(path):
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            yield line.split("\t")


def main():
    vocab = {n: dict(en=en, aisle=a, unit=u) for n, en, a, u in tsv(ROOT / "tools/ingredients.tsv")}
    dishes = {d["id"] for d in json.loads((ROOT / "data/dishes.js").read_text(encoding="utf-8").split("=", 1)[1].rstrip().rstrip(";"))}
    recipes, bad = {}, []
    for f in tsv(ROOT / "tools/recipes.tsv"):
        did, toks = f[0], (f[1] if len(f) > 1 else "")
        if did not in dishes:
            bad.append(did); continue
        items = []
        for tok in filter(None, (t.strip() for t in toks.split(";"))):
            qty = None
            m = re.match(r"^(.*):(\d+(?:\.\d+)?)$", tok)
            if m: tok, qty = m.group(1), float(m.group(2))
            if "~" in tok:
                name, en, aisle, unit = (tok.split("~") + ["", "", "g"])[:4]
                vocab.setdefault(name, dict(en=en, aisle=aisle, unit=unit if unit in ("g", "个") else "g"))
            else:
                name = tok
                if name not in vocab:
                    print("unknown ingredient (skipped):", did, name); continue
            if vocab[name]["aisle"].startswith(PANTRY): qty = None
            if any(i[0] == name for i in items): continue
            items.append([name, int(qty) if qty is not None and qty == int(qty) else qty])
        if items: recipes[did] = items
    used = Counter(i[0] for r in recipes.values() for i in r)
    ing = {n: vocab[n] for n in used}
    out = ROOT / "data/recipes.js"
    out.write_text("// generated by tools/build_recipes.py - do not edit by hand\nwindow.ING = " + json.dumps(ing, ensure_ascii=False, separators=(",", ":"))
                   + ";\nwindow.RECIPES = " + json.dumps(recipes, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(len(recipes), "of", len(dishes), "dishes have recipes;", len(ing), "ingredients;", len(bad), "unknown dish ids")
    if "--report" in sys.argv:
        print("single-use ingredients:", [n for n, c in used.items() if c == 1])
        print("dishes without recipe:", sorted(dishes - set(recipes))[:40])


main()
